--==============CREACION INFORMES============
--Informe 1: Asociaciones de fútbol profesional
--Lista las asociaciones que cumplan con las siguientes condiciones:
--Sean de tipo profesional (P).
--Hayan sido creadas después del año 2000.
--Se ordenen de manera descendente según su fecha de creación.
SELECT
    cod_asociacion AS "ID ASOCIACION",
    nombre_asociacion AS "NOMBRE ASOCIACION",
    TO_CHAR(fecha_creacion, 'DD-MM-YYYY') AS "FECHA CREACION",
    tipo_asociacion AS "TIPO ASOCIACION"
FROM ASOCIACION
WHERE tipo_asociacion = 'P'
  AND fecha_creacion >= DATE '2001-01-01'
ORDER BY fecha_creacion DESC;

--Informe 2: Patrimonio de clubes de fútbol
--Genera un informe con el patrimonio de los clubes expresado en pesos chilenos y su
--conversión a dólares, considerando un tipo de cambio de $955 por dólar.
--Incluye únicamente los clubes que cumplan con las siguientes condiciones:
--Su nombre contenga la letra a.
--Su patrimonio sea superior a $200.000.000.
--Sean de tipo profesional.
--Los resultados se ordenen de manera descendente según el código del club.
SELECT
    cod_club AS "CODIGO CLUB",
    nombre_club AS "NOMBRE CLUB",
    patrimonio AS "PATRIMONIO CLP",
    ROUND(patrimonio / 955, 2) AS "PATRIMONIO USD",
    tipo_club AS "TIPO CLUB"
FROM CLUB_FUTBOL
WHERE LOWER(nombre_club) LIKE '%a%'
  AND patrimonio > 200000000
  AND tipo_club = 'Profesional'
ORDER BY cod_club DESC;




















